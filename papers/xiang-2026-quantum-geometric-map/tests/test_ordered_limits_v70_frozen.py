"""v70 independent regeneration of multi-frequency frozen finite-lead data.

The full 1000-site production values are separately regenerated by
test_ordered_limits_v70.py at omega=.29; omega=.20 and .40 are explicit
finite-length calculations from the frozen paper experiment, not freshly
re-evaluated in this quick CI gate. They remain CONDITIONAL.
"""
import importlib.util,json,pathlib,unittest
import numpy as np

class V70Frozen(unittest.TestCase):
    def test_quick_three_frequency_independent_regeneration(self):
        root=pathlib.Path(__file__).resolve().parents[1]
        spec=importlib.util.spec_from_file_location('v70_reproduce',root/'scripts/reproduce_v70_ordered_limits.py')
        mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
        actual=mod.create(False)
        frozen=json.loads((root/'results/frozen/v70_ordered_limits.json').read_text())
        def compare(a,b,name='root'):
            if isinstance(a,(float,int)) and not isinstance(a,bool):
                self.assertTrue(np.isfinite(a) and np.isfinite(b),name)
                self.assertLess(abs(a-b),3e-9,name)
            elif isinstance(a,dict):
                self.assertEqual(a.keys(),b.keys(),name)
                for k,v in a.items():compare(v,b[k],name+'.'+str(k))
            elif isinstance(a,list):
                self.assertEqual(len(a),len(b),name)
                for i,(x,y) in enumerate(zip(a,b)):compare(x,y,name+f'[{i}]')
            else:self.assertEqual(a,b,name)
        for label in ('quick_sequence','keldysh_reference'):
            compare(actual[label],frozen[label],label)

if __name__=='__main__':unittest.main()
