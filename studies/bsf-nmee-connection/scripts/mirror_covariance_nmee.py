"""Independent physical Hamiltonian covariance test for BSF layer NMEE.

Two 8-band partner Hamiltonians are related EXACTLY by horizontal-mirror
unitary (layer swap and spin-1/2 rotation). The model is synthetic; its
relative shift is a connection label, not a microscopic hopping-vs-shift fit.
Use the original Jia et al. clean band kernel (two response protocols) without
modifying the frozen paper reproduction.
"""
import json
import os
import sys
from pathlib import Path
import numpy as np

repo_root=Path(__file__).resolve().parents[3]
paper=Path(os.environ.get('NMEE_PAPER_DIR',str(repo_root/'papers/jia-2026-nonlin-magnetoelectric-edelstein')))
sys.path.insert(0,str(paper))
from nmee_lab.clean_core.core import BlochModel, mesh, integrate_chunked, layer_spin
from nmee_lab.clean_core.models import kane_mele, I2, SX, SZ

TAUX=np.array([[0,1],[1,0]],complex)
TAUZ=np.diag([1,-1]).astype(complex)
P_TOP=(I2+TAUZ)/2
P_BOTTOM=(I2-TAUZ)/2
S_X=np.kron(I2,np.kron(I2,SX))
S_Z=np.kron(I2,np.kron(I2,SZ))
U_MIRROR=np.kron(TAUX,np.kron(I2,SZ))  # global phase i immaterial


def make_models(t0=.003,t1=.006,delta=.002):
    mono=kane_mele()
    atom_z=np.kron(np.diag([1,-1]),I2)
    hop=(t0*np.kron(TAUX,np.eye(4))+
         t1*np.kron(TAUX,atom_z)+
         delta*np.kron(TAUZ,np.eye(4)))
    top=layer_spin(S_X,np.kron(P_TOP,np.eye(4)))
    bottom=layer_spin(S_X,np.kron(P_BOTTOM,np.eye(4)))
    sig={'top_x':top, 'bottom_x':bottom, 'total_x':S_X, 'z':S_Z}
    model=[]
    for partner in (False,True):
        def tform(mat, partner=partner):
            return U_MIRROR@mat@U_MIRROR.conj().T if partner else mat
        def H(k, tform=tform):
            base=mono.hamiltonian(k)
            return tform(np.kron(I2,base)+hop)
        def velocity(k, axis, tform=tform):
            return tform(np.kron(I2,mono.velocity(k,axis)))
        ops={name:(lambda k,v=v: np.broadcast_to(v,(len(k),8,8)).copy()) for name,v in sig.items()}
        model.append(BlochModel(H,velocity,ops,mono.reciprocal,g_factor=mono.g_factor,
                                name=('mirror-partner' if partner else 'source')))
    return model


def calculate(mesh_n=11,temperature=0.,mu=.025):
    source,mirror=make_models()
    k=mesh(source.reciprocal,mesh_n)
    observables=('top_x','bottom_x','total_x')
    results={}
    for name,model in [('tau1',source),('tau2',mirror)]:
        results[name]={}
        for o in observables:
            val=integrate_chunked(model,k,alpha=o,gamma='z',beta=0,mu=mu,
                                  temperature_K=temperature,chunk_size=256)
            results[name][o]={p:float(val[p]) for p in ('printed','full_static')}
        # Record the actual model gap separately, not assume the input mu is insulating.
        e=np.linalg.eigvalsh(model.hamiltonian(k))
        results[name]['sampled_midgap_eV']=[float(e[:,3].max()),float(e[:,4].min())]
        results[name]['sampled_min_adjacent_eV']=float(np.diff(e,axis=1).min())
    tests={}
    for protocol in ('printed','full_static'):
        s=results['tau1'];d=results['tau2']
        scale=max(1e-8,abs(s['total_x'][protocol]),abs(d['total_x'][protocol]))
        tests[protocol]={
            'total_mirror_odd_error':float(abs(d['total_x'][protocol]+s['total_x'][protocol])),
            'top_from_bottom_error':float(abs(d['top_x'][protocol]+s['bottom_x'][protocol])),
            'bottom_from_top_error':float(abs(d['bottom_x'][protocol]+s['top_x'][protocol])),
            'top_bottom_sum_error':float(abs(s['top_x'][protocol]+s['bottom_x'][protocol]-s['total_x'][protocol])),
            'relative_tolerance_base':float(scale),
        }
        assert max(tests[protocol][k] for k in ('total_mirror_odd_error','top_from_bottom_error','bottom_from_top_error','top_bottom_sum_error')) < 1e-8*scale+1e-12
    assert results['tau1']['sampled_midgap_eV'][0]<mu<results['tau1']['sampled_midgap_eV'][1], 'Fermi level not in sampled gap'
    # Hamiltonian covariance across random k plus Zeeman covariance and layer operators.
    rng=np.random.default_rng(20261019);kr=rng.normal(size=(7,2));u=U_MIRROR
    assert np.max(abs(mirror.hamiltonian(kr)-u@source.hamiltonian(kr)@u.conj().T))<1e-12
    assert np.max(abs(u@S_X@u.conj().T+S_X))<1e-12
    assert np.max(abs(u@S_Z@u.conj().T-S_Z))<1e-12
    return {'model':'8-band synthetic mirror-related Kane-Mele bilayer',
            'connection':'m_z: (1/3,2/3) -> (2/3,1/3), exchange top/bottom',
            'note':'Mirror partner is generated by unitary; nonzero amplitude is not a material prediction or independently simulated sliding path.',
            'mesh_n':mesh_n,'temperature_K':temperature,'mu_eV':mu,
            't0_eV':.003,'t1_eV':.006,'delta_eV':.002,
            'results':results,'checks':tests}

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--mesh',type=int,default=11)
    p.add_argument('--output',default=None);args=p.parse_args()
    out=calculate(mesh_n=args.mesh)
    content=json.dumps(out,indent=2,ensure_ascii=False)
    if args.output:Path(args.output).write_text(content+'\n',encoding='utf-8')
    print(content)
